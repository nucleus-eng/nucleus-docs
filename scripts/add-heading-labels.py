#!/usr/bin/env python3
"""add-heading-labels.py — give every heading under docs/ a unique MyST label.

style-guide/conventions.md requires a label on the line above each heading:

    (reporter-degfp-requirements)=
    # Requirements

MyST binds a link fragment by global identifier and ignores the file path, so
a heading called Overview on one page can capture a link meant for another
page. A label of the form `<page-directory>-<section-slug>` makes each target
unique. This script derives the label from the page's directory name and the
heading text, writes it above the heading, and leaves everything else alone.

The slug is MyST's own rule (`myst_html_id` in check-links.py), so a label is
what MyST would have normalized it to anyway.

Rules:
  * An existing label on the line above a heading is kept unchanged.
  * Headings inside code fences, `:::` directives (tab-sets, admonitions,
    cards), HTML comments and front matter get no label.
  * A "# Supported by" heading gets none either: build-devnote-cards.py
    deletes and rewrites that section, and would orphan a label above it.
  * Hub pages are out of scope (see EXCLUDED_PAGES) until the hub-page
    question is ruled.
  * A label is never guessed. If two headings would take the same label, or a
    candidate matches a label that already exists anywhere in docs/, guides/
    or about/, every colliding heading is reported and none is written.
  * Re-running changes nothing: a second run finds every heading labeled.

Usage:
    python3 scripts/add-heading-labels.py                 # label every page under docs/
    python3 scripts/add-heading-labels.py <file.md> ...   # these pages only
    python3 scripts/add-heading-labels.py --dry-run       # report, write nothing
    python3 scripts/add-heading-labels.py --check         # write nothing; fail if a heading lacks a label

Exit codes: 0 nothing to do (or labels written), 1 --check found a heading
without a label, or a collision was reported, 2 could not run.
"""
import argparse
import importlib.util
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
DOCS = REPO / "docs"
# Labels are unique across everything MyST publishes, not only docs/.
LABEL_ROOTS = ("docs", "guides", "about")

# Hub and index pages. Whether a hub heading takes a label is an open question
# (J30), so these are skipped and listed rather than decided here.
EXCLUDED_PAGES = {
    "docs/modules/modules-main.md": "hub: index of every module",
    "docs/processes/processes-main.md": "hub: index of every process",
    "docs/implementations/implementations-main.md": "hub: index of every implementation",
    "docs/processes/make-protein/make-protein-main.md": "hub: parent page that lists the protein sub-processes",
    "docs/dna-distro.md": "index: landing page with no page directory of its own (directory is docs/)",
}

# Generated by scripts/build-devnote-cards.py, which rewrites the section.
GENERATED_HEADINGS = {"Supported by"}

HEADING = re.compile(r"^(#{1,6})\s+(.*?)(?:\s+#+)?\s*$")
LABEL = re.compile(r"^\(([^)\s][^)]*)\)=\s*$")
FENCE = re.compile(r"^(\s*)(`{3,}|~{3,})")
COLON_OPEN = re.compile(r"^\s*(:{3,})\s*\S")
COLON_CLOSE = re.compile(r"^\s*(:{3,})\s*$")


def _load_links():
    spec = importlib.util.spec_from_file_location("check_links", REPO / "scripts" / "check-links.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


LINKS = _load_links()


def rel(path: pathlib.Path) -> str:
    return path.resolve().relative_to(REPO).as_posix()


def heading_text(raw: str) -> str:
    """Heading text with inline markdown reduced to its words."""
    title = raw
    for pattern, repl in LINKS._INLINE_MD:
        title = pattern.sub(repl, title)
    return title


def make_label(page: pathlib.Path, raw_heading: str) -> str:
    """`<page-directory>-<section-slug>`, normalized the way MyST normalizes it."""
    return LINKS.myst_html_id(f"{page.resolve().parent.name} {heading_text(raw_heading)}")


def scan(path: pathlib.Path):
    """Walk one page. Returns (headings, labels).

    headings: list of dicts {line (0-based), raw, label_above (str|None), skip (str|None)}
    labels:   every `(x)=` target found on the page, outside code fences
    """
    lines = path.read_text(encoding="utf-8").splitlines()
    headings, labels = [], []
    i = 0
    if lines and lines[0].strip() == "---":
        for j in range(1, len(lines)):
            if lines[j].strip() == "---":
                i = j + 1
                break
    fence = None            # (char, length) while inside a code fence
    colon_depth = []        # stack of open `:::` lengths
    in_comment = False
    for n in range(i, len(lines)):
        line = lines[n]
        m = FENCE.match(line)
        if fence:
            if m and m.group(2)[0] == fence[0] and len(m.group(2)) >= fence[1] \
                    and not line.strip()[len(m.group(2)):].strip():
                fence = None
            continue
        if m:
            fence = (m.group(2)[0], len(m.group(2)))
            continue
        if in_comment:
            if "-->" in line:
                in_comment = False
            continue
        if "<!--" in line and "-->" not in line.split("<!--", 1)[1]:
            in_comment = True
            continue
        close = COLON_CLOSE.match(line)
        if close and colon_depth:
            # A longer closer also ends any unclosed inner fence (an author's
            # `::::` item closed by `:::::` leaves no directive open).
            while colon_depth and colon_depth[-1] <= len(close.group(1)):
                colon_depth.pop()
            continue
        opener = COLON_OPEN.match(line)
        if opener:
            colon_depth.append(len(opener.group(1)))
            continue
        lab = LABEL.match(line.strip())
        if lab and not colon_depth:
            labels.append((n, lab.group(1)))
            continue
        h = HEADING.match(line)
        if h:
            above = None
            if n > 0:
                prev = LABEL.match(lines[n - 1].strip())
                if prev:
                    above = prev.group(1)
            skip = None
            if colon_depth:
                skip = "inside a directive (tab-set, admonition or card)"
            elif h.group(2).strip() in GENERATED_HEADINGS:
                skip = "generated section (build-devnote-cards.py)"
            headings.append({"line": n, "raw": h.group(2).strip(), "label_above": above, "skip": skip})
    return headings, labels


def in_scope_pages(args_paths):
    if args_paths:
        return [pathlib.Path(p).resolve() for p in args_paths]
    return sorted(p.resolve() for p in DOCS.rglob("*.md") if "generated" not in p.parts)


def existing_labels():
    """normalized label -> list of 'file:line' for every label in the published roots."""
    seen: dict[str, list[str]] = {}
    for root in LABEL_ROOTS:
        base = REPO / root
        if not base.is_dir():
            continue
        for p in sorted(base.rglob("*.md")):
            if "generated" in p.parts:
                continue
            _, labels = scan(p)
            for n, name in labels:
                seen.setdefault(LINKS.myst_html_id(name), []).append(f"{rel(p)}:{n + 1}")
    return seen


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("files", nargs="*", help="pages to process (default: every page under docs/)")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if a heading lacks a label")
    ap.add_argument("--dry-run", action="store_true", help="report what would change; write nothing")
    args = ap.parse_args(argv)

    pages = in_scope_pages(args.files)
    taken = existing_labels()

    plans = {}       # page -> list of (heading dict, label)
    skipped = {}     # reason -> count
    excluded = []
    counts = {"headings": 0, "labeled": 0}
    cand: dict[str, list] = {}   # candidate label -> [(page, heading)]

    for page in pages:
        if not page.is_file() or page.suffix != ".md":
            continue
        key = rel(page)
        if key in EXCLUDED_PAGES:
            excluded.append(key)
            continue
        headings, _ = scan(page)
        for h in headings:
            if h["skip"]:
                skipped[h["skip"]] = skipped.get(h["skip"], 0) + 1
                continue
            counts["headings"] += 1
            if h["label_above"]:
                counts["labeled"] += 1
                continue
            label = make_label(page, h["raw"])
            if not label:
                cand.setdefault("", []).append((page, h))
                continue
            cand.setdefault(label, []).append((page, h))

    collisions = []
    for label, owners in sorted(cand.items()):
        if not label:
            collisions.append((label, owners, []))
            continue
        clash = taken.get(label, [])
        if len(owners) > 1 or clash:
            collisions.append((label, owners, clash))
            continue
        page, h = owners[0]
        plans.setdefault(page, []).append((h, label))

    missing = sum(len(v) for v in plans.values()) + sum(len(o) for _, o, _ in collisions)

    if not args.check and not args.dry_run:
        for page, items in plans.items():
            lines = page.read_text(encoding="utf-8").split("\n")
            for h, label in sorted(items, key=lambda t: -t[0]["line"]):
                lines.insert(h["line"], f"({label})=")
            page.write_text("\n".join(lines), encoding="utf-8")

    verb = "need a label" if args.check else ("would add" if args.dry_run else "added")
    n_labels = sum(len(v) for v in plans.values())
    print(f"{len(pages) - len(excluded)} page(s) read; {counts['headings']} heading(s) in scope, "
          f"{counts['labeled']} already labeled.")
    print(f"{n_labels} label(s) {verb} on {len(plans)} page(s).")
    if args.check:
        for page, items in sorted(plans.items()):
            for h, label in items:
                print(f"  {rel(page)}:{h['line'] + 1}  missing ({label})=")
    for reason, n in sorted(skipped.items()):
        print(f"skipped {n} heading(s): {reason}")
    if excluded:
        print(f"excluded {len(excluded)} page(s):")
        for key in excluded:
            print(f"  {key}  [{EXCLUDED_PAGES[key]}]")
    if collisions:
        print(f"❌ {len(collisions)} collision(s); no label written for these headings:")
        for label, owners, clash in collisions:
            print(f"  ({label})=" if label else "  (no slug)=")
            for page, h in owners:
                print(f"      wanted by {rel(page)}:{h['line'] + 1}  '{h['raw']}'")
            for where in clash:
                print(f"      already defined at {where}")
    if args.check:
        return 1 if missing else 0
    return 1 if collisions else 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except SystemExit:
        raise
    except Exception as exc:  # noqa: BLE001 — tooling breakage is exit 2, not a finding
        print(f"error: {type(exc).__name__}: {exc}", file=sys.stderr)
        sys.exit(2)
